/* =============================================================================
   D15-G. БЭК-ТЕСТ ПОВТОРНОГО ДЕФОЛТА НА ПОМЕСЯЧНОЙ СЕТКЕ БАЗЫ ДЕФОЛТОВ.

   ЧТО УСТАНОВЛЕНО ПРОГОНОМ 27.08.2026 И ДЕЛАЕТ ЭТОТ СКРИПТ ВОЗМОЖНЫМ.
   181 колонка '01.02.2012' … '01.02.2027' в HISTORY_DEFAULT_ACCOUNT содержит
   ПОМЕСЯЧНЫЙ DPD. Сверка с CL_PORTFOLIO_2.dpd на двух датах дала точное
   совпадение: 229207 из 229207 на 01.08.2026 и 254491 из 254491 на 01.05.2026,
   при нуле нечитаемых значений. Совпадений с category — 7 из 229207, то есть
   случайные.

   СЛЕДСТВИЕ. Выгрузка В1 из DATA_REQUEST.md по помесячной просрочке НЕ НУЖНА:
   история глубиной 15 лет, одна строка на счёт, уже лежит в базе. Бэк-тест
   строится сегодня.

   ЧТО ИМЕННО СЧИТАЕТСЯ. Для каждого оздоровлённого счёта берётся окно
   в @Window месяцев ПЕРЕД health_date и по нему определяется, каким правилом
   счёт прошёл бы отбор:

     strict — все срезы окна DPD = 0            (действующее правило Методики)
     soft   — все срезы DPD <= @Soft, но не все 0  (что добавляет инициатива)
     neither — окно не проходит ни то, ни другое

   Исход — повторный дефолт: new_default_date позже health_date.

   ГИПОТЕЗА, КОТОРУЮ ЭТО ПРОВЕРЯЕТ ПЕРВОЙ И КОТОРАЯ МОЖЕТ ПЕРЕВЕРНУТЬ ЗАДАЧУ.
   Если в группе neither окажется заметная доля, значит правило «DPD = 0 шесть
   месяцев подряд» исторически НЕ ПРИМЕНЯЛОСЬ как написано. Тогда инициатива
   не смягчает правило, а приводит документ в соответствие с практикой,
   и предъявлять её надо именно так.

   ОГРАНИЧЕНИЯ, КОТОРЫЕ ОСТАЮТСЯ.
     * Структура вмещает максимум ДВА эпизода на счёт: default_date -> health_date
       и new_default_date -> new_health_date. Счёт, дефолтивший трижды,
       неотличим от дефолтившего дважды. Все величины — нижние границы.
     * Снимок даёт нижнюю границу эпизода, не его величину (П2). Окно из шести
       нулей на срезах не означает шести месяцев без просрочки.
     * Когорты 2025-2026 незрелые: у них не было времени сорваться. Сравнивать
       только когорты с полным горизонтом наблюдения.

   Read-only. Только SELECT. #temp с префиксом D15G_. MAXDOP 1.
   Все секции запускать в одном окне подряд: временные таблицы локальные.
   T-SQL (Microsoft SQL Server).
   ============================================================================= */

