/* -----------------------------------------------------------------------------
   § 3. Классификация окна: каким правилом счёт прошёл бы отбор.
   ----------------------------------------------------------------------------- */
IF OBJECT_ID('tempdb..#D15G_class') IS NOT NULL DROP TABLE #D15G_class;

SELECT
      p.account_number
    , COUNT(*)                                   AS months_obs
    , MAX(p.dpd)                                 AS dpd_max
    , MIN(p.dpd)                                 AS dpd_min
    , CASE
        WHEN COUNT(*) < @Window            THEN 'incomplete  окно неполное'
        WHEN MAX(p.dpd) = 0                THEN 'strict  все срезы DPD = 0'
        WHEN MAX(p.dpd) <= @Soft           THEN 'soft  все срезы <= порога, но не нули'
        ELSE                                    'neither  окно не проходит ни одно правило'
      END                                        AS rule_group
INTO #D15G_class
FROM #D15G_panel p
GROUP BY p.account_number
OPTION (MAXDOP 1);

CREATE UNIQUE CLUSTERED INDEX ix_D15G_class ON #D15G_class(account_number);

/* -----------------------------------------------------------------------------
   § 4. ГЛАВНАЯ ТАБЛИЦА. Ставка повторного дефолта по группам правил.
        Читать сверху вниз: если neither весом сопоставим со strict —
        правило Методики исторически не применялось как написано.
   ----------------------------------------------------------------------------- */
SELECT
      k.rule_group
    , COUNT(*)                                   AS cured
    , SUM(c.redefaulted)                         AS redefaulted
    , CAST(100.0 * SUM(c.redefaulted) / NULLIF(COUNT(*),0) AS decimal(5,2)) AS rd_rate_pct
    , SUM(CASE WHEN c.months_to_rd <= @Hor THEN 1 ELSE 0 END)               AS rd_within_hor
    , CAST(100.0 * SUM(CASE WHEN c.months_to_rd <= @Hor THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                            AS rd_hor_pct
    , CAST(AVG(CAST(k.dpd_max AS float)) AS decimal(6,2))                   AS avg_dpd_max
FROM #D15G_class k
INNER JOIN #D15G_cured c ON c.account_number = k.account_number
GROUP BY k.rule_group
ORDER BY k.rule_group
OPTION (MAXDOP 1);

/* -----------------------------------------------------------------------------
   § 5. То же по когортам оздоровления. Когорты 2025-2026 незрелые —
        у них не было времени сорваться, низкая ставка там не улучшение.
   ----------------------------------------------------------------------------- */
SELECT
      YEAR(c.health_date)                        AS cure_year
    , k.rule_group
    , COUNT(*)                                   AS cured
    , SUM(c.redefaulted)                         AS redefaulted
    , CAST(100.0 * SUM(c.redefaulted) / NULLIF(COUNT(*),0) AS decimal(5,2)) AS rd_rate_pct
FROM #D15G_class k
INNER JOIN #D15G_cured c ON c.account_number = k.account_number
WHERE YEAR(c.health_date) <= YEAR(DATEADD(MONTH, -@Hor, GETDATE()))
GROUP BY YEAR(c.health_date), k.rule_group
ORDER BY cure_year, k.rule_group
OPTION (MAXDOP 1);

/* -----------------------------------------------------------------------------
   § 6. Скорость срыва по группам. Срыв в первом квартале означает,
        что оздоровление было фиктивным независимо от правила.
   ----------------------------------------------------------------------------- */
SELECT
      k.rule_group
    , CASE WHEN c.months_to_rd <= 3  THEN '0-3'
           WHEN c.months_to_rd <= 6  THEN '4-6'
           WHEN c.months_to_rd <= 12 THEN '7-12'
           WHEN c.months_to_rd <= 24 THEN '13-24'
           ELSE '25+' END                        AS bucket
    , COUNT(*)                                   AS accounts
FROM #D15G_class k
INNER JOIN #D15G_cured c ON c.account_number = k.account_number
WHERE c.redefaulted = 1
GROUP BY k.rule_group,
      CASE WHEN c.months_to_rd <= 3  THEN '0-3'
           WHEN c.months_to_rd <= 6  THEN '4-6'
           WHEN c.months_to_rd <= 12 THEN '7-12'
           WHEN c.months_to_rd <= 24 THEN '13-24'
           ELSE '25+' END
ORDER BY k.rule_group, bucket
OPTION (MAXDOP 1);

/* -----------------------------------------------------------------------------
   § 7. Чувствительность к порогу. Отвечает на вопрос «почему именно 15»:
        строится ставка повторного дефолта для порогов 5, 10, 15, 20, 25, 30.
        Если кривая плоская до 30 — порог 15 выбран произвольно, и это надо
        сказать самим. Если растёт после 15 — выбор обоснован данными.
   ----------------------------------------------------------------------------- */
SELECT
      t.thr                                      AS soft_threshold
    , SUM(CASE WHEN k.dpd_max <= t.thr THEN 1 ELSE 0 END)                    AS cured_pass
    , SUM(CASE WHEN k.dpd_max <= t.thr THEN c.redefaulted ELSE 0 END)        AS redefaulted
    , CAST(100.0 * SUM(CASE WHEN k.dpd_max <= t.thr THEN c.redefaulted ELSE 0 END)
           / NULLIF(SUM(CASE WHEN k.dpd_max <= t.thr THEN 1 ELSE 0 END),0)
           AS decimal(5,2))                                                  AS rd_rate_pct
FROM #D15G_class k
INNER JOIN #D15G_cured c ON c.account_number = k.account_number
CROSS JOIN (VALUES (0),(5),(10),(15),(20),(25),(30),(60),(90)) t(thr)
WHERE k.rule_group <> 'incomplete  окно неполное'
GROUP BY t.thr
ORDER BY t.thr
OPTION (MAXDOP 1);
