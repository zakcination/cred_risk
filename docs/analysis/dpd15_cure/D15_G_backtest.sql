      d.account_number
    , d.default_date
    , d.health_date
    , d.new_default_date
    , d.fact_close_date
    , d.[type]
    , CASE WHEN d.new_default_date IS NOT NULL
            AND d.new_default_date > d.health_date THEN 1 ELSE 0 END AS redefaulted
    , CASE WHEN d.new_default_date IS NOT NULL
