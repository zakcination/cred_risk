/* ---------------------------------------------------------------------------
   ЧТО ЧИТАТЬ В РЕЗУЛЬТАТЕ

   1. ИТОГО при tau=0  — действующее правило. Это база.
   2. ИТОГО при tau=15 — портфель под новым правилом. Разница = цена решения.
   3. SOFT-ONLY при tau=15 — предельная ставка: только добавленные займы.
   4. «возврат_30plus» против «без_форы»: если разрыв SOFT-ONLY против STRICT
      есть в первой колонке и исчезает во второй — весь эффект был арифметикой
      снимка, заёмщики не хуже. Если выживает в обеих — заёмщики действительно
      хуже, и это довод против инициативы.
   5. Форма кривой по восьми tau важнее любой отдельной пары значений:
      излом указывает на порог, монотонность без излома — на его отсутствие,
      и тогда выбор 15 остаётся нормативным (RESEARCH_PROTOCOL.md § 7).

   ДАЛЬШЕ, на той же цепочке отдельными прогонами:
     * продукты: соединить fin с
       (SELECT account_number, MAX(subproduct) AS subproduct
          FROM [IFRS9].[dbo].[KAN_20260801_for_LGD_Fenix] GROUP BY account_number),
       клетки HAVING COUNT(*) >= 100 — правило утверждено до расчёта.
       SELECT * по этой таблице запрещён: во второй колонке ИИН;
     * чистый прирост против ускорения: разбить SOFT-ONLY при tau=15
       по health_date IS NULL.
   --------------------------------------------------------------------------- */
