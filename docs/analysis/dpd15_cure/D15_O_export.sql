/* =============================================================================
   D15-O. СТРУКТУРНАЯ ВЫГРУЗКА ДЛЯ САМОСТОЯТЕЛЬНОЙ ПРОВЕРКИ.

   Назначение: отдать не мои агрегаты, а строки, из которых они получаются.
   Одна строка = один заём при одном пороге tau. Всё, что есть в отчёте,
   получается из этой таблицы сводной таблицей Excel. Ни одной величины,
   которую нельзя пересчитать самому.

   ###########################################################################
   #  КОНФИДЕНЦИАЛЬНОСТЬ. Выгрузка содержит номера договоров и В РЕПОЗИТОРИЙ  #
   #  НЕ КОММИТИТСЯ и за периметр банка не выносится. В репозитории живёт     #
   #  только этот скрипт (CLAUDE.md § 2: «Код сбора — да, собранные данные —  #
   #  нет»). Если файл нужно кому-то передать — сначала удалить колонку       #
   #  account_number.                                                        #
   ###########################################################################

   ЧТО ЛЕЖИТ В КАЖДОЙ СТРОКЕ

     ИЗМЕРЕНИЯ (по чему строить сводную)
       account_number   номер договора — ключ для сверки с источником
       default_date     дата дефолта из журнала
       vintage_year     год дефолта — для разреза по винтажам
       vintage_qtr      квартал дефолта
       subproduct       продукт из PD/LGD-источника; NULL = не сматчился
       tau              порог, при котором заём попал в выборку
       exit_month       месяц выхода t, отсчёт от даты дефолта
       grp              STRICT = вышел бы и без смягчения; SOFT-ONLY = добавлен

     ОКНО НАБЛЮДЕНИЯ, помесячно — видно, что именно проверял критерий
       w1 … w6          просрочка на каждую из шести отчётных дат окна,
                        w6 — последняя, она же месяц выхода t

     ПОСЛЕ ВЫХОДА
       dpd_pause        просрочка на t+1  (месяц паузы, в исход не входит)
       dpd_out1         просрочка на t+2  \  окно исхода
       dpd_out2         просрочка на t+3  /
       out_max          максимум из dpd_out1 и dpd_out2

     ФЛАГИ ИСХОДА — каждый 0 или 1, определение написано рядом
       f_return30       out_max > 30                     основной исход
       f_delta30        out_max − w6 >= 30               исход без форы снимка
       f_cured_fact     health_date заполнена            вылечен фактически
       f_redef_reg      отметка в журнале после выхода   реестровый срыв

   КАК ИЗ ЭТОГО ПОЛУЧАЕТСЯ КАЖДАЯ ЦИФРА ОТЧЁТА (сводная таблица)

     строки = tau, значение = СРЗНАЧ(f_return30)      -> кривая порога
     фильтр tau=0, строки = exit_month                -> ранние против поздних
     строки = vintage_year, фильтр tau=0              -> разрез по винтажам
     строки = subproduct, фильтр tau=15               -> продуктовый разрез
     строки = grp, фильтр tau=15                      -> добавленные против базы
     значение = СРЗНАЧ(f_delta30) вместо f_return30   -> та же цифра без форы

   Знаменатель везде один и тот же: СЧЁТ строк в клетке. Никаких взвешиваний,
   никаких пересчётов между клетками. Что делится на что — видно в сводной.

   ГРАНИЦЫ ВЫГРУЗКИ, названы прямо
     * когорта — дефолты 2019-01 … 2025-10; более поздние не имеют полного
       горизонта наблюдения при сетке, заполненной по 2026-08;
     * окно ищется до 36-го месяца от дефолта; заём, у которого чистое окно
       складывается позже, в выгрузку не попадает;
     * строка появляется, только если наблюдаемы ВСЕ шесть месяцев окна
       и оба месяца исхода. Частично наблюдаемые займы отброшены;
     * приостановка начисления не исключена — поля под неё не нашлось
       ни в одной базе. Такие займы в выгрузке ЕСТЬ и помечены быть не могут.

   Источники:
     [CL_PORTFOLIO].[dbo].[HISTORY_DEFAULT_ACCOUNT]  займы, даты, сетка DPD
     [IFRS9].[dbo].[KAN_20260801_for_LGD_Fenix]      только продукт;
                                                     SELECT * запрещён, ИИН

   Read-only. Только SELECT. Без временных таблиц. MAXDOP 1.
   Ожидаемый объём: около 229 тыс. строк, помещается в лист Excel.
   ============================================================================= */

