function cell(text,w,o={}){const parts=Array.isArray(text)?text:[text];
  return new TableCell({width:{size:w,type:WidthType.DXA},
    shading:o.shade?{type:ShadingType.CLEAR,fill:o.shade,color:'auto'}:undefined,
    margins:{top:50,bottom:50,left:70,right:70},verticalAlign:'center',
    children:parts.map((t,i)=>new Paragraph({spacing:{after:i===parts.length-1?0:50,line:230},alignment:o.align,
      children:[new TextRun({text:String(t),bold:o.b,size:o.size||18})]}))});}
function TBL(widths,rows,opts={}){const hdr=opts.headerRows===undefined?1:opts.headerRows;
  return new Table({width:{size:widths.reduce((a,b)=>a+b,0),type:WidthType.DXA},columnWidths:widths,
    rows:rows.map((r,ri)=>new TableRow({tableHeader:ri<hdr,
      children:r.map((c,ci)=>cell(c,widths[ci],{b:ri<hdr,size:opts.size,
        shade:ri<hdr?GREY:(opts.shadeRows&&opts.shadeRows.includes(ri)?LIGHT:undefined),
        align:(opts.rightCols&&opts.rightCols.includes(ci)&&ri>=hdr)?AlignmentType.RIGHT:undefined}))}))});}

