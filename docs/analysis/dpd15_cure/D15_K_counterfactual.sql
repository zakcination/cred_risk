/* -----------------------------------------------------------------------------
   § 3. СКОЛЬЗЯЩЕЕ ОКНО [t-5; t] И ГОРИЗОНТ ИСХОДА — одним проходом.
        obs6      — сколько непустых месяцев в окне; правило применимо при 6
        wmax      — максимум DPD в окне
        fwd_max   — максимум DPD в @Hor месяцах ПОСЛЕ t: это и есть исход
   ----------------------------------------------------------------------------- */
IF OBJECT_ID('tempdb..#D15K_roll') IS NOT NULL DROP TABLE #D15K_roll;

SELECT
      account_number
    , m
    , dpd
    , COUNT(dpd) OVER (PARTITION BY account_number ORDER BY m
                       ROWS BETWEEN 5 PRECEDING AND CURRENT ROW)        AS obs6
    , MAX(dpd)   OVER (PARTITION BY account_number ORDER BY m
                       ROWS BETWEEN 5 PRECEDING AND CURRENT ROW)        AS wmax
    , MAX(dpd)   OVER (PARTITION BY account_number ORDER BY m
                       ROWS BETWEEN 1 FOLLOWING AND 12 FOLLOWING)       AS fwd12
    , MAX(dpd)   OVER (PARTITION BY account_number ORDER BY m
                       ROWS BETWEEN 1 FOLLOWING AND 6  FOLLOWING)       AS fwd6
    , MAX(dpd)   OVER (PARTITION BY account_number ORDER BY m
                       ROWS BETWEEN 1 FOLLOWING AND 24 FOLLOWING)       AS fwd24
    , COUNT(dpd) OVER (PARTITION BY account_number ORDER BY m
                       ROWS BETWEEN 1 FOLLOWING AND 12 FOLLOWING)       AS fwd12_obs
INTO #D15K_roll
FROM #D15K_panel
OPTION (MAXDOP 1);

CREATE CLUSTERED INDEX ix_D15K_roll ON #D15K_roll(account_number, m);

/* -----------------------------------------------------------------------------
   § 4. ПЕРВЫЙ МЕСЯЦ, В КОТОРОМ ПРАВИЛО ВЫПОЛНЕНО. Контрфактическая дата выхода.
        Раньше седьмого месяца от дефолта оздоровление невозможно по механизму,
        поэтому m >= @Window.
   ----------------------------------------------------------------------------- */
IF OBJECT_ID('tempdb..#D15K_first') IS NOT NULL DROP TABLE #D15K_first;

SELECT
      account_number
    , MIN(CASE WHEN obs6 = @Window AND wmax = 0     THEN m END)  AS m_strict
    , MIN(CASE WHEN obs6 = @Window AND wmax <= @Soft THEN m END) AS m_soft
INTO #D15K_first
FROM #D15K_roll
WHERE m >= @Window
GROUP BY account_number
OPTION (MAXDOP 1);

CREATE UNIQUE CLUSTERED INDEX ix_D15K_first ON #D15K_first(account_number);

/* -----------------------------------------------------------------------------
   § 5. КЛАССИФИКАЦИЯ И ИСХОД.
        SOFT-ONLY — прошёл мягкое и НЕ проходил строгое к тому же месяцу.
        Это и есть прирост от инициативы, ради которого всё считается.
   ----------------------------------------------------------------------------- */
IF OBJECT_ID('tempdb..#D15K_res') IS NOT NULL DROP TABLE #D15K_res;

SELECT
      f.account_number
    , CASE WHEN f.m_soft IS NULL                       THEN 'NEVER     не прошёл ни одно правило'
           WHEN f.m_strict IS NOT NULL
            AND f.m_strict <= f.m_soft                 THEN 'STRICT    вышел бы и по действующему'
           ELSE                                             'SOFT-ONLY прирост от инициативы' END AS rule_group
    , f.m_soft                                         AS m_cure
    , r.fwd6, r.fwd12, r.fwd24, r.fwd12_obs
    , c.health_date
    , c.default_date
INTO #D15K_res
FROM #D15K_first f
INNER JOIN #D15K_coh c  ON c.account_number = f.account_number
LEFT  JOIN #D15K_roll r ON r.account_number = f.account_number AND r.m = f.m_soft
OPTION (MAXDOP 1);

/* -----------------------------------------------------------------------------
   § 6. ГЛАВНАЯ ТАБЛИЦА КОНТУРА.
        Строка SOFT-ONLY против строки STRICT и есть ответ на вопрос
        «безопасно ли смягчение».
   ----------------------------------------------------------------------------- */
SELECT
      rule_group
    , COUNT(*)                                                              AS accounts
    , SUM(CASE WHEN fwd6  > @DefThr THEN 1 ELSE 0 END)                      AS def_6m
    , CAST(100.0 * SUM(CASE WHEN fwd6  > @DefThr THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                            AS def_6m_pct
    , SUM(CASE WHEN fwd12 > @DefThr THEN 1 ELSE 0 END)                      AS def_12m
    , CAST(100.0 * SUM(CASE WHEN fwd12 > @DefThr THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                            AS def_12m_pct
    , SUM(CASE WHEN fwd24 > @DefThr THEN 1 ELSE 0 END)                      AS def_24m
    , CAST(100.0 * SUM(CASE WHEN fwd24 > @DefThr THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                            AS def_24m_pct
    , CAST(AVG(CAST(m_cure AS float)) AS decimal(5,1))                      AS avg_month_of_cure
FROM #D15K_res
GROUP BY rule_group
ORDER BY rule_group
OPTION (MAXDOP 1);

-- 6a. То же по когортам года дефолта. Поздние когорты незрелые:
--     у них не было @Hor месяцев, чтобы дефолтнуть заново.
SELECT
      YEAR(default_date)                                                    AS default_year
    , rule_group
    , COUNT(*)                                                              AS accounts
    , CAST(100.0 * SUM(CASE WHEN fwd12 > @DefThr THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                            AS def_12m_pct
    , SUM(CASE WHEN fwd12_obs < 12 THEN 1 ELSE 0 END)                       AS immature
FROM #D15K_res
GROUP BY YEAR(default_date), rule_group
ORDER BY default_year, rule_group
OPTION (MAXDOP 1);

-- 6b. КОНТРОЛЬ АДЕКВАТНОСТИ. Группа STRICT должна в основном совпадать
--     с фактически вылеченными. Если совпадение низкое — реконструкция
--     правила неверна, и таблицу § 6 предъявлять нельзя.
SELECT
      rule_group
    , COUNT(*)                                                  AS accounts
    , SUM(CASE WHEN health_date IS NOT NULL THEN 1 ELSE 0 END)  AS actually_cured
    , CAST(100.0 * SUM(CASE WHEN health_date IS NOT NULL THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                AS actually_cured_pct
    , CAST(AVG(CASE WHEN health_date IS NOT NULL
                    THEN CAST(DATEDIFF(MONTH, default_date, health_date) - m_cure AS float) END)
           AS decimal(5,1))                                     AS avg_month_gap
FROM #D15K_res
GROUP BY rule_group
ORDER BY rule_group
OPTION (MAXDOP 1);

/* -----------------------------------------------------------------------------
   § 7. КРИВАЯ ПО ПОРОГАМ на ПРАВИЛЬНОЙ популяции: не среди вылеченных,
        а среди всех дефолтнувших. Отвечает на «почему именно 15».
        Для каждого порога берётся первый проходящий месяц ПО КАЖДОМУ СЧЁТУ.
   ----------------------------------------------------------------------------- */
;WITH pass AS (
    SELECT r.account_number, r.m, r.wmax, r.fwd12
    FROM #D15K_roll r
    WHERE r.m >= @Window AND r.obs6 = @Window
),
firsts AS (
    SELECT t.thr, p.account_number, p.fwd12
         , ROW_NUMBER() OVER (PARTITION BY t.thr, p.account_number ORDER BY p.m) AS rn
    FROM (VALUES (0),(5),(10),(15),(20),(25),(30)) t(thr)
    INNER JOIN pass p ON p.wmax <= t.thr
)
SELECT
      thr                                                                   AS soft_threshold
    , COUNT(*)                                                              AS would_cure
    , SUM(CASE WHEN fwd12 > @DefThr THEN 1 ELSE 0 END)                      AS def_12m
    , CAST(100.0 * SUM(CASE WHEN fwd12 > @DefThr THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                            AS def_12m_pct
FROM firsts
WHERE rn = 1
GROUP BY thr
ORDER BY thr
OPTION (MAXDOP 1);

/* -----------------------------------------------------------------------------
   § 8. РАЗРЕЗ ПО ПРОДУКТАМ. Автономен: продукт берётся напрямую из IFRS9,
        зависимости от D15-J больше нет. Правило минимальной клетки — 100 займов.
   ----------------------------------------------------------------------------- */
SELECT
      p.subproduct
    , r.rule_group
    , COUNT(*)                                                              AS accounts
    , CAST(100.0 * SUM(CASE WHEN r.fwd12 > @DefThr THEN 1 ELSE 0 END)
           / NULLIF(COUNT(*),0) AS decimal(5,2))                            AS def_12m_pct
FROM #D15K_res r
INNER JOIN (
    SELECT account_number, MAX(subproduct) AS subproduct
    FROM [IFRS9].[dbo].[KAN_20260801_for_LGD_Fenix]
    GROUP BY account_number
) p ON p.account_number = r.account_number
GROUP BY p.subproduct, r.rule_group
HAVING COUNT(*) >= 100
ORDER BY p.subproduct, r.rule_group
OPTION (MAXDOP 1);


