/* =============================================================================
   D15-K. ГЛАВНЫЙ РАСЧЁТ КОНТУРА.
   Какой была бы ставка дефолта, если бы правило DPD <= 15 применялось раньше.

   ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ ВСЕГО, ЧТО СЧИТАЛОСЬ ДО СИХ ПОР — И ЭТО ГЛАВНОЕ.

   D15-G и D15-H брали УЖЕ ОЗДОРОВЛЁННЫЕ счета и классифицировали окно перед
   выходом. Это отвечает на вопрос «как вели себя те, кого вылечили».
   Вопрос контура другой: «что было бы с теми, кого НЕ вылечили по строгому
   правилу, но вылечили бы по мягкому». Такие счета в популяции оздоровлённых
   ОТСУТСТВУЮТ по определению — они остались в дефолте. Считать надо
   по ДЕФОЛТНОЙ популяции, а не по вылеченной.

   КОНСТРУКЦИЯ.
   Для каждого счёта и каждого месяца t внутри его дефолтного эпизода
   оценивается скользящее окно [t-5; t] — ровно то окно, которое проверяет банк
   (механизм подтверждён владельцем: заём, дефолтнувший 7 месяцев назад,
   проверяется на шесть чистых месяцев подряд, и health_date ставится по итогам
   прогона, то есть совпадает с t).

       STRICT   — все шесть месяцев DPD = 0        (действующее правило)
       SOFT     — все шесть месяцев DPD <= @Soft   (предлагаемое)
       SOFT-ONLY — прошёл SOFT, но не STRICT       <-- ПРИРОСТ ОТ ИНИЦИАТИВЫ

   Берётся ПЕРВЫЙ месяц t, в котором правило выполнено: это контрфактическая
   дата оздоровления. Дальше окно не оценивается — заём считается вышедшим.

   ИСХОД. Наступил ли дефолт заново в течение @Hor месяцев после t.
   Признаком служит DPD > @DefThr (90 дней, наш признак обесценения
   по Приложению 4 п. 5 пп. 1), а НЕ флаг корзины и не health_date.
   Причина принципиальная: флаг стадии и даты выхода формируются тем самым
   правилом, которое мы тестируем. Порог 90 от правила не зависит и применим
   к обеим группам одинаково — в том числе к SOFT-ONLY, которые фактически
   из дефолта не выходили и «повторно дефолтнуть» в терминах флага не могут.

   СМЕЩЕНИЕ, КОТОРОЕ ОСТАЁТСЯ И КОТОРОЕ НАДО РАСКРЫТЬ САМИМ.
   Группа SOFT-ONLY фактически оставалась в дефолте и весь период наблюдения
   получала работу коллекшна, которую вышедший заём не получает. Направление
   смещения известно — в сторону ОПТИМИЗМА; величина неизвестна. Поэтому
   критерий приемлемости должен иметь запас, и это записывается ДО расчёта.

   Read-only. Только SELECT. #temp с префиксом D15K_. MAXDOP 1.
   Все секции — в одном окне подряд.
   T-SQL (Microsoft SQL Server).
   ============================================================================= */

