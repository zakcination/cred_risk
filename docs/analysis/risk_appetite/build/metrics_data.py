def load_rb():
    """Девять розничных метрик: (код, название, сегмент, лимит, 36 значений)."""
    with open(RB_CSV, encoding="utf-8") as fh:
        rows = [r for r in fh if not r.startswith("#")]
    rd = list(csv.reader(rows, delimiter=";"))
    out = []
    for row in rd[1:]:
        out.append((row[0], TITLES[row[0]], row[1], float(row[2]),
                    [float(x) for x in row[3:]]))
    return rd[0][3:], out


