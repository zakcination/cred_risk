H("Приложение. Что говорить по слайдам", 16, 0)
P("Спикерские заметки из презентации, по одному абзацу на слайд.", size=10, color=MUT, after=10)
pres=Presentation("RA_top20_zones.pptx")
for i,sl in enumerate(pres.slides,1):
    t=""
    for sh in sl.shapes:
        if sh.has_text_frame and sh.text_frame.text.strip():
            t=sh.text_frame.text.strip().split("\n")[0]; break
    note=sl.notes_slide.notes_text_frame.text.strip() if sl.has_notes_slide else ""
    H("Слайд %d. %s" % (i, t[:90]), 11.5, 8, NAVY)
    if note: P(note, size=10.5, after=4)

d.save("RA_top20_zapiska.docx")
