def build():
    rows = load_rows()
    wb = Workbook()
    wb.remove(wb.active)
    k_row = sheet_series(wb, rows)
    p = sheet_params(wb, k_row)
    calc = sheet_calc(wb)
    basis = sheet_basis(wb, calc)
    extra = sheet_zones(wb, calc)
    extra += sheet_sigmas(wb, calc)
    extra += sheet_triggers(wb)
    rb_first, _ = sheet_metrics_data(wb)
    extra += sheet_metrics(wb, calc, rb_first)
    sheet_guide(wb)
    placed = add_images(wb)

    names = {
        "v": f"'Ряд'!$H${FIRST}:$H${LAST}",
        "d": f"'Ряд'!$J${FIRST + 1}:$J${LAST}",
        "cor_kb": f"'Ряд'!$O${FIRST}:$O${LAST}",
        "d_cor_kb": f"'Ряд'!$P${FIRST + 1}:$P${LAST}",
        "cor_ms": f"'Ряд'!$R${FIRST}:$R${LAST}",
        "d_cor_ms": f"'Ряд'!$S${FIRST + 1}:$S${LAST}",
    }
    for nm, cell in p.items():
        names[nm] = f"'Параметры'!${cell[0]}${cell[1:]}"
    for nm, ref in names.items():
        wb.defined_names[nm] = DefinedName(nm, attr_text=ref)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    wb.save(OUT)
    return OUT, calc.checks + basis.checks + extra, placed


def verify(path, checks):
    """Вычислить формулы книги движком `formulas` и сверить с опубликованным.

    Считает не «то же самое на python», а сами формулы листа — проверяется то,
    что увидит Excel. Опубликованные значения хранятся здесь, а не в ячейках:
    колонки сверки с листов убраны, чтобы книга читалась на комитете, но контроль
    от этого не исчез. Движок в зависимостях репозитория не значится; без него
    сверка не выполняется и об этом говорится прямо.
    """
    try:
        import formulas
    except ImportError:
        raise RuntimeError(
            "движок формул не установлен: pip install formulas.\n"
            "Без него сверить книгу нечем — python-пересчёт проверял бы "
            "собственную реализацию, а не формулы листа."
        )
    import warnings
    warnings.filterwarnings("ignore")
    xl = formulas.ExcelModel().loads(path).finish()
    sol = xl.calculate()
    book = {}
    for key, val in sol.items():
        ks = str(key)
        if "!" not in ks:
            continue
        sheet = ks.split("]")[-1].split("!")[0].rstrip("'")
        try:
            book[(sheet, ks.split("!")[-1])] = val.value[0, 0]
        except Exception:
            book[(sheet, ks.split("!")[-1])] = None

    bad = []
    for sheet, addr, want, tol in checks:
        got = book.get((sheet, addr))
        row_no = re.sub(r"^[A-Z]+", "", addr)
        label = book.get((sheet, "A" + row_no)) if row_no else None
        if got is None or isinstance(got, str):
            bad.append(f"  {sheet}!{addr} ({label}): не вычислилось -> {got!r}")
            continue
        if abs(float(got) - float(want)) > tol:
            bad.append(f"  {sheet}!{addr} ({label}): {float(got):.6f} против "
                       f"{float(want):.6f}, допуск {tol}")
    return bad, len(checks)


def main():
    path, checks, placed = build()
    total = len(checks)
    print(f"собрано: {os.path.relpath(path, HERE)}  ({total} сверяемых чисел)")
    print(f"иллюстраций вставлено: {len(placed)}" +
          ("  — " + "; ".join(placed) if placed else ""))
    if "--verify" not in sys.argv:
        print("сверка не запускалась — для неё нужен ключ --verify")
        return 0
    bad, total = verify(path, checks)
    if bad:
        print(f"РАСХОЖДЕНИЙ: {len(bad)} из {total}")
        print("\n".join(bad))
        return 1
    print(f"сверка пройдена: все {total} чисел вычислены по формулам самой книги "
          f"и сошлись с опубликованными")
    return 0


