def calc_normality_table(ws, start, rb_first=5):
    """Короткий расчёт нормальности по каждой из двенадцати метрик.

    Моменты считаются через SUMPRODUCT, а НЕ через СКОС и ЭКСЦЕСС: встроенные
    функции Excel возвращают исправленные на смещение оценки, а критерий
    Жарк-Бера построен на выборочных моментах. Подстановка одного вместо
    другого дала бы неверную статистику при верно выглядящей формуле.

    Шапиро-Уилк и Андерсон-Дарлинг в Excel без макросов не воспроизводятся
    (первому нужна таблица коэффициентов, второму — сортировка ряда). Внесены
    константами и помечены ⚠ — второе объявленное исключение книги после
    бутстрапа.
    """
    heads = [("A", "Метрика"), ("B", "Ряд приращений"), ("C", "Вердикт формальный"),
             ("D", "Жарк-Бера"), ("E", "Что это значит для метода"),
             ("F", "Асим."), ("G", "Экс."), ("H", "p(ЖБ)"), ("I", "Шапиро p ⚠"),
             ("J", "Андерсон ⚠"), ("K", "M(4) модель"), ("L", "Q90(4м) факт"),
             ("M", "Расх., %"), ("N", "МЕТОД")]
    for col, t in heads:
        put(ws, f"{col}{start}", t, F_HEAD, fill=HEAD_BG, border=True,
            align=Alignment(wrap_text=True, vertical="bottom"))
    for col, w in (("F", 8), ("G", 8), ("H", 9), ("I", 10), ("J", 10),
                   ("K", 11), ("L", 11), ("M", 10), ("N", 24), ("O", 9),
                   ("P", 6), ("Q", 10), ("R", 11), ("S", 11), ("T", 11)):
        ws.column_dimensions[col].width = w
    ws.row_dimensions[start].height = 34
    put(ws, f"P{start}", "n", F_MUTED, border=True)
    put(ws, f"Q{start}", "среднее", F_MUTED, border=True)
    for c, t in (("R", "m₂"), ("S", "m₃"), ("T", "m₄")):
        put(ws, f"{c}{start}", t, F_MUTED, border=True)

    checks, r = [], start + 1
    for code, name, d_rng, w_rng in norm_ranges(rb_first):
        sk, ku, jb, pj, sw, ad, mdl, fact, dev = NORM_EXPECTED[code]
        put(ws, f"A{r}", name, F_BODY, align=WRAP, border=True)
        put(ws, f"B{r}", d_rng.replace("'", ""), F_MONO, align=WRAP, border=True)
        put(ws, f"P{r}", f"=COUNT({d_rng})", F_MUTED, "0", border=True)
        put(ws, f"Q{r}", f"=AVERAGE({d_rng})", F_MUTED, "0.0000", border=True)
        for c, pw in (("R", 2), ("S", 3), ("T", 4)):
            put(ws, f"{c}{r}", f"=SUMPRODUCT(({d_rng}-Q{r})^{pw})/P{r}",
                F_MUTED, "0.000000", border=True)
        put(ws, f"F{r}", f"=S{r}/R{r}^1.5", F_BODY, "0.000", border=True)
        put(ws, f"G{r}", f"=T{r}/R{r}^2", F_BODY, "0.00", border=True)
        put(ws, f"D{r}", f"=P{r}/6*(F{r}^2+(G{r}-3)^2/4)", F_BLOCK, "0.000",
            border=True)
        put(ws, f"H{r}", f"=CHIDIST(D{r},2)", F_BODY, "0.0000", border=True)
        put(ws, f"I{r}", sw, F_MUTED, "0.0000", border=True)
        put(ws, f"J{r}", ad, F_MUTED, "0.0000", border=True)
        formal = pj > 0.05 and sw > 0.05 and ad < 0.752
        put(ws, f"C{r}", f'=IF(AND(H{r}>alpha,I{r}>alpha,J{r}<ad_crit),'
                         f'"нормально","НЕ нормально")', F_BODY, border=True,
            align=CENTER, fill=GREEN_BG if formal else RED_BG)
        put(ws, f"K{r}", f"=z_p*STDEV({d_rng})*SQRT(4)", F_BODY, "0.0000",
            border=True)
        put(ws, f"L{r}", f"=PERCENTILE({w_rng},p_conf)", F_BODY, "0.0000",
            border=True)
        put(ws, f"M{r}", f"=(K{r}-L{r})/ABS(L{r})*100", F_BLOCK, "0.00",
            border=True)
        # «Вырожден» — отдельное состояние: буфер на цикл реагирования не
        # помещается в сам лимит, и граница зелёной уходит за него. Формально
        # это крайний случай завышения, практически — непригодность метода.
        put(ws, f"O{r}", f"='Метрики'!C{MET_ROW[code]}", F_MUTED, "0.0000",
            border=True)
        put(ws, f"N{r}",
            f'=IF(K{r}>=O{r},"ЗАМЕНА: вырожден",'
            f'IF(ABS(M{r})<=tau*100,"M(T) — совпадает",'
            f'IF(M{r}<0,"ЗАМЕНА: занижает","M(T) — консервативна")))',
            F_BLOCK, align=WRAP, border=True)
        put(ws, f"E{r}", MEANING[code], F_MUTED, align=WRAP, border=True)
        ws.row_dimensions[r].height = 30
        for c, pub, tol in (("F", sk, 0.0005), ("G", ku, 0.005),
                            ("D", jb, 0.0005), ("H", pj, 0.00005),
                            ("K", mdl, 0.00005), ("L", fact, 0.00005),
                            ("M", dev, 0.0005)):
            checks.append(("РАСЧЁТ", f"{c}{r}", pub, tol))
        r += 1
    return checks


