#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Стресс-якорь: уровень риск-аппетита как граница выживания в сценарии.

Назначение. Уровень риск-аппетита определяется не тем, как метрика колебалась
(это M(T), см. `build/raschet_list.py`), а тем, где она окажется в утверждённом
сценарии. Граница зелёной зоны — такое базовое значение, при котором стрессовое
значение ЕЩЁ укладывается в лимит:

    S(v_зел) = L      ⟹      v_зел = S⁻¹(L)

Для мультипликативной передачи S(v) = v·m это даёт v_зел = L/m, то есть границу
в процентах лимита, равную 1/m. Тем самым «процент лимита» перестаёт быть
подобранным числом и становится следствием сценария.

Основание метода — не наше изобретение:
  • ECB *Guide to the ICAAP* (2018), принцип 7: аппетит привязывается
    к достаточности под неблагоприятным сценарием;
  • EBA/GL/2018/04 «Guidelines on institutions' stress testing», в т.ч. § 4.7
    об обратном стресс-тестировании;
  • PRA SS31/15 (ICAAP/SREP);
  • OCC Heightened Standards, 12 CFR ч. 30 прил. D, II.E — лимиты привязываются
    к риск-ёмкости.

    python3 stress_anchor.py            # таблицы в stdout
    python3 stress_anchor.py --csv      # + ../data/stress_anchor_boundaries.csv

────────────────────────────────────────────────────────────────────────────
ЧТО ЭТОТ СКРИПТ СЧИТАТЬ НЕ МОЖЕТ И ПОЧЕМУ

Заполненных результатов стресс-теста у контура НЕТ — получены все семь
приложений Методики, но только как шаблоны (реестр, блок МС; п. 55 требует Ф.27
ежемесячно, п. 50-23 — общеэкономический сценарий не реже раза в год).
Отсюда три границы применимости, и обходить их подстановкой правдоподобных
чисел нельзя:

  1. PD-метрики  — считаются. Приложение № 4 даёт база→кризис по трём продуктам.
  2. EL-метрики  — НЕ считаются. EL = PD × LGD; сценарий даёт множитель PD.
     Перенести его на EL значит принять LGD неизменной, чему противоречат
     Приложения № 5 и № 6 (модели LGD по недвижимости и автотранспорту).
     Нужен множитель LGD того же сценария.
  3. Топ-20, CoR, капитальные и ликвидные — НЕ считаются прямой формой.
     Передача идёт через капитал, стрессовый капитал считается на листе 1.2
     Приложения № 2, а он у нас пустой шаблон. Для них считается ОБРАТНАЯ
     форма: какой шок выводит метрику на лимит. Обратный стресс-тест — не
     суррогат, а самостоятельное требование EBA/GL/2018/04 § 4.7.

ЖЁСТКОСТЬ СЦЕНАРИЯ ОБЪЯВЛЯЕТСЯ ВМЕСТЕ С РЕЗУЛЬТАТОМ. Негативный и кризисный
сценарии Приложения № 4 совпадают по всем шести макровходам и всем девяти
выходам; калибровка на 2020 год; по потребительскому портфелю кризис добавляет
к PD 0,61 пп (экспонат 8). Якорь наследует мягкость сценария целиком: зелёная
зона, полученная на мягком сценарии, — мягкая зелёная зона.
"""

import argparse
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "build"))
from metrics_data import load_rb                          # noqa: E402

DATA = os.path.join(HERE, "..", "data")
T20 = os.path.join(DATA, "top20_monthly_2023_08_2026_07.csv")
OUT_CSV = os.path.join(DATA, "stress_anchor_boundaries.csv")

# ── сценарий ──────────────────────────────────────────────────────────────
# Приложение № 4 к Методике стресс-тестирования (СД, протокол № 03 от
# 12.01.2015, ред. 21.09.2022), строки 25 и 48. Значения перенесены при
# разборе приложения; перед комитетом сверить с оригиналом.
SCENARIO = {
    "потребительский":  (12.53, 13.14),
    "автокредитование": (4.75, 6.16),
    "ипотека":          (1.70, 2.19),
}

# ── соответствие продукт ↔ метрика ────────────────────────────────────────
# ВЫБОР АВТОРА, НЕ СКРИПТА (§ 6 корневого CLAUDE.md). Уровни не совпадают
# численно — Приложение № 4 даёт PD потребительский 12,53 против 10,96 в нашем
# ряде, — поэтому переносится МНОЖИТЕЛЬ, а не уровень; но какому продукту
# отвечает «обеспеченные» и «прочие», из данных не следует.
#   None = соответствие не установлено: метрика считается по ВСЕМ трём
#   множителям, и в таблице видно, насколько ответ от выбора зависит.
MAPPING = {
    "pd_unsecured":       "потребительский",
    "pd_unsecured_cash":  "потребительский",
    "pd_unsecured_goods": "потребительский",
    "pd_secured":         None,     # ипотека или автокредитование?
    "pd_other":           None,     # автокредитование?
}


def multipliers():
    return {k: c / b for k, (b, c) in SCENARIO.items()}


def load_top20():
    with open(T20, encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh, delimiter=";"))
    r = rows[-1]
    return r["date"], float(r["zaim_mln"]), float(r["sk_new_mln"])


def block_scenario():
    print("СЦЕНАРИЙ — Приложение № 4, строки 25 и 48. Негативный = кризисный.\n")
    print(f"{'продукт':20s} {'база':>7s} {'кризис':>8s} {'Δ, пп':>7s} "
          f"{'m':>8s} {'1/m, % лимита':>15s}")
    for k, (b, c) in SCENARIO.items():
        m = c / b
        print(f"{k:20s} {b:7.2f} {c:8.2f} {c - b:+7.2f} {m:8.4f} {100 / m:14.1f} %")
    print("\nКалибровка на 2020 год. Якорь наследует мягкость сценария.\n")


def block_forward():
    """Прямая форма: v_зел = L/m. Только PD — по EL см. шапку, ограничение 2."""
    m = multipliers()
    _dates, rb = load_rb()
    rows = []
    print("=" * 78)
    print("ПРЯМАЯ ФОРМА — граница зелёной = L/m. ТОЛЬКО PD-метрики.\n")
    print(f"{'метрика':30s} {'факт':>8s} {'лимит':>7s} {'продукт':>17s} "
          f"{'граница':>9s} {'% лимита':>9s} {'запас, пп':>10s}")
    for code, name, seg, lim, vals in rb:
        if not code.startswith("pd_"):
            continue
        v = vals[-1]
        prod = MAPPING.get(code)
        keys = [prod] if prod else list(SCENARIO)
        for i, k in enumerate(keys):
            g = lim / m[k]
            tag = k if prod else f"({k})"
            fact_s = f"{v:8.4f}" if i == 0 else " " * 8
            lim_s = f"{lim:7.2f}" if i == 0 else " " * 7
            print(f"{name if i == 0 else '':30s} {fact_s} {lim_s} {tag:>17s} "
                  f"{g:9.2f} {100 / m[k]:8.1f} % {g - v:10.4f}")
            rows.append(dict(metric=code, name=name, segment=seg, limit=lim,
                             fact=v, product=k, mapped=bool(prod),
                             green=round(g, 4), pct_of_limit=round(100 / m[k], 2),
                             headroom=round(g - v, 4)))
        if not prod:
            print(f"{'':30s} {'':8s} {'':7s} "
                  f"{'← соответствие не установлено, решает автор':>60s}")
    print("\nEL-метрики (4 шт.) здесь отсутствуют сознательно: нужен множитель")
    print("LGD того же сценария, иначе якорь занижен. См. шапку, ограничение 2.\n")
    return rows


def block_reverse():
    """Обратная форма для топ-20: какой шок капитала выводит на лимит."""
    date, zaim, sk = load_top20()
    print("=" * 78)
    print("ОБРАТНАЯ ФОРМА — топ-20. EBA/GL/2018/04 § 4.7.\n")
    print(f"Дата среза {date}. Числитель (задолженность топ-20) {zaim:,.1f} млн ₸,")
    print(f"собственный капитал {sk:,.1f} млн ₸, коэффициент {100 * zaim / sk:.4f} %.\n")
    print(f"{'предел':34s} {'нужный капитал':>16s} {'шок капитала':>14s} {'состояние':>12s}")
    rows = []
    for label, L in (("регуляторный уровень 95 %", 95.0),
                     ("уровень с поправкой Г26 (108,63 %)", 95.0 / (439961.267 / 503086.114))):
        need = zaim / (L / 100)
        shock = 100 * (need - sk) / sk
        state = "уже за пределом" if shock > 0 else f"запас {-shock:.2f} %"
        print(f"{label:34s} {need:16,.1f} {shock:+13.2f} % {state:>12s}")
        rows.append(dict(metric="top20_to_equity", name="Топ-20 / СК", segment="KB",
                         limit=round(L, 4), fact=round(100 * zaim / sk, 4),
                         product="обратный стресс", mapped=False,
                         green="", pct_of_limit="", headroom=round(-shock, 4)))
    print("\nДля сравнения — фактический шок капитала Q1 2026: −19,66 %.")
    print("Он втрое превышает падение, которого достаточно для выхода на предел")
    print("с поправкой Г26. То есть требуемая жёсткость сценария уже наблюдалась.\n")
    return rows


# Приложение № 2 к Методике: уровень и порог красной зоны у восьми метрик
# с ограничением снизу. Перенесено при разборе приложения (viz/charts.py::ex6).
PRIL2 = [("k1", 8.5, 9.0), ("k1-2", 9.5, 10.0), ("k2", 11.0, 11.5),
         ("ACARI", 13.0, 14.0), ("HLA", 20.0, 25.0), ("LCR", 105.0, 110.0),
         ("NSFR", 105.0, 110.0), ("ALRI", 85.0, 90.0)]


def block_convergence():
    """Три независимых пути к границе в процентах лимита. Сходятся ли."""
    m = multipliers()
    mir = sorted((200 - 100 * red / lim, n) for n, lim, red in PRIL2)
    core = [(x, n) for x, n in mir if x > 94]          # плотная группа
    out = [(x, n) for x, n in mir if x <= 94]
    print("=" * 78)
    print("СХОДИМОСТЬ: три независимых пути к границе в процентах лимита\n")
    print(f"  1. Действующая практика Банка — Приложение № 2, порог красной зоны,")
    print(f"     зеркально для метрик с потолком: {core[0][0]:.1f}–{core[-1][0]:.1f} % "
          f"({len(core)} метрик из {len(mir)});")
    print(f"     вне группы: " + ", ".join(f"{n} {x:.1f} %" for x, n in out))
    lo, hi = min(100 / x for x in m.values()), max(100 / x for x in m.values())
    print(f"  2. Стресс-якорь — граница зелёной 1/m: {lo:.1f}–{hi:.1f} % "
          f"в зависимости от продукта")
    print(f"     (мягкий потребительский {100 / m['потребительский']:.1f} %, "
          f"жёсткое авто {100 / m['автокредитование']:.1f} %)")
    print(f"  3. Предложение автора — лестница 85 % / 95 %\n")
    print("  Числа близки, НО означают разное: в Приложении № 2 это порог КРАСНОЙ,")
    print("  в стресс-якоре — граница ЗЕЛЁНОЙ. Совпадение величины при расхождении")
    print("  роли — самостоятельный вопрос к комитету, а не подтверждение.\n")
    print(f"  Диапазон сценария {lo:.1f}–{hi:.1f} % ровно накрывает предложенную")
    print(f"  лестницу. Если зелёная должна означать «переживает сценарий по")
    print(f"  ХУДШЕМУ продукту», её граница — {lo:.1f} %, а не 85 %.\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", action="store_true", help="записать CSV границ")
    a = ap.parse_args()

    block_scenario()
    rows = block_forward()
    rows += block_reverse()
    block_convergence()

    print("=" * 78)
    print("НЕ ПОСЧИТАНО И ПОЧЕМУ")
    print("  4 EL-метрики        — нужен множитель LGD сценария (Прил. № 5, № 6)")
    print("  2 CoR               — передача через капитал; плюс открыта Д15")
    print("  13 некредитных      — стрессовый капитал/ликвидность: лист 1.2")
    print("                        Приложения № 2 у нас пустой шаблон")
    print("  Итого: из 25 метрик прямой формой закрыто 5, обратной 1, открыто 19.\n")

    if a.csv:
        with open(OUT_CSV, "w", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0]), delimiter=";")
            w.writeheader()
            w.writerows(rows)
        print("записано", os.path.relpath(OUT_CSV, HERE))


if __name__ == "__main__":
    main()
